CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  nim TEXT NOT NULL DEFAULT '',
  bio TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kategori (
  id INTEGER PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  ikon TEXT NOT NULL DEFAULT '🍽️',
  deskripsi TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS tempat (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  kategori_id INTEGER NOT NULL REFERENCES kategori(id) ON DELETE RESTRICT,
  alamat TEXT NOT NULL DEFAULT 'Tidak diketahui',
  harga INTEGER NOT NULL DEFAULT 0,
  rating REAL NOT NULL DEFAULT 0,
  deskripsi TEXT NOT NULL DEFAULT 'Belum ada deskripsi.',
  foto_url TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  jam_buka TEXT NOT NULL DEFAULT 'Tidak diketahui',
  populer BOOLEAN NOT NULL DEFAULT false,
  osm_id TEXT,
  dibuat_oleh INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sumber TEXT NOT NULL DEFAULT 'kurasi',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Migrasi ringan untuk database yang dibuat sebelum fitur kontribusi pengguna.
ALTER TABLE tempat ADD COLUMN IF NOT EXISTS dibuat_oleh INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE tempat ADD COLUMN IF NOT EXISTS sumber TEXT NOT NULL DEFAULT 'kurasi';

CREATE INDEX IF NOT EXISTS idx_tempat_kategori ON tempat (kategori_id);
CREATE INDEX IF NOT EXISTS idx_tempat_nama ON tempat (nama);
CREATE INDEX IF NOT EXISTS idx_tempat_dibuat_oleh ON tempat (dibuat_oleh);
CREATE INDEX IF NOT EXISTS idx_tempat_created_at ON tempat (created_at DESC);

-- API mengakses database lewat koneksi Postgres langsung (role owner),
-- jadi RLS tidak mengganggu. Ini menutup akses anon/authenticated via
-- PostgREST kalau kunci anon Supabase bocor.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE kategori ENABLE ROW LEVEL SECURITY;
ALTER TABLE tempat ENABLE ROW LEVEL SECURITY;
