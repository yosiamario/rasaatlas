CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  nim TEXT NOT NULL DEFAULT '',
  bio TEXT NOT NULL DEFAULT '',
  role TEXT NOT NULL DEFAULT 'user',
  avatar_url TEXT NOT NULL DEFAULT '',
  email_verified BOOLEAN NOT NULL DEFAULT false,
  reset_token TEXT,
  reset_expires TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS kategori (
  id INTEGER PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  ikon TEXT NOT NULL DEFAULT '🍽️',
  deskripsi TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS tempat (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  kategori_id INTEGER NOT NULL REFERENCES kategori(id) ON DELETE RESTRICT,
  alamat TEXT NOT NULL DEFAULT 'Tidak diketahui',
  harga INTEGER NOT NULL DEFAULT 0,
  rating REAL NOT NULL DEFAULT 0,
  deskripsi TEXT NOT NULL DEFAULT 'Belum ada deskripsi.',
  foto_url TEXT NOT NULL DEFAULT '',
  lat DOUBLE PRECISION,
  lng DOUBLE PRECISION,
  jam_buka TEXT NOT NULL DEFAULT 'Tidak diketahui',
  populer BOOLEAN NOT NULL DEFAULT false,
  osm_id TEXT,
  dibuat_oleh INTEGER REFERENCES users(id) ON DELETE SET NULL,
  sumber TEXT NOT NULL DEFAULT 'kurasi',
  status TEXT NOT NULL DEFAULT 'approved',
  catatan_moderasi TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Migrasi ringan untuk database yang dibuat sebelum kolom baru ditambahkan
ALTER TABLE users ADD COLUMN IF NOT EXISTS role TEXT NOT NULL DEFAULT 'user';
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_url TEXT NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_token TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS reset_expires TIMESTAMPTZ;

ALTER TABLE tempat ADD COLUMN IF NOT EXISTS dibuat_oleh INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE tempat ADD COLUMN IF NOT EXISTS sumber TEXT NOT NULL DEFAULT 'kurasi';
ALTER TABLE tempat ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'approved';
ALTER TABLE tempat ADD COLUMN IF NOT EXISTS catatan_moderasi TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);
CREATE INDEX IF NOT EXISTS idx_tempat_kategori ON tempat (kategori_id);
CREATE INDEX IF NOT EXISTS idx_tempat_nama ON tempat (nama);
CREATE INDEX IF NOT EXISTS idx_tempat_dibuat_oleh ON tempat (dibuat_oleh);
CREATE INDEX IF NOT EXISTS idx_tempat_status ON tempat (status);
CREATE INDEX IF NOT EXISTS idx_tempat_created_at ON tempat (created_at DESC);

-- Tabel Favorit (Bookmark)
CREATE TABLE IF NOT EXISTS favorit (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tempat_id INTEGER NOT NULL REFERENCES tempat(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, tempat_id)
);

CREATE INDEX IF NOT EXISTS idx_favorit_user ON favorit (user_id);
CREATE INDEX IF NOT EXISTS idx_favorit_tempat ON favorit (tempat_id);

-- Tabel Ulasan & Rating Pengguna
CREATE TABLE IF NOT EXISTS ulasan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tempat_id INTEGER NOT NULL REFERENCES tempat(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  rating INTEGER NOT NULL CHECK (rating >= 1 AND rating <= 5),
  komentar TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (tempat_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_ulasan_tempat ON ulasan (tempat_id);
CREATE INDEX IF NOT EXISTS idx_ulasan_user ON ulasan (user_id);
CREATE INDEX IF NOT EXISTS idx_ulasan_created_at ON ulasan (created_at DESC);

